export type CopyKey = keyof typeof es;
export function t(key: CopyKey, values: Record<string, string | number> = {}): string {
  return es[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
}
export function enumText(value: string): string {
  const key = `enum.${value}`;
  return key in es ? t(key as CopyKey) : value;
}
